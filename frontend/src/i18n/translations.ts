import type { SupportedLang } from '../types/api';

export function formatUzs(amount: number, lang: SupportedLang): string {
  const formatted = Math.round(amount)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  if (lang === 'ru') return `${formatted} сум`;
  if (lang === 'uz_cyrl') return `${formatted} сўм`;
  return `${formatted} so‘m`;
}

